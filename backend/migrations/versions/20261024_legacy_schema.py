def _split_sql(script: str) -> list[str]:
    """Разбить скрипт PostgreSQL по точкам с запятой вне кавычек и долларовых блоков."""
    statements: list[str] = []
    start = 0
    index = 0
    quote: str | None = None
    dollar_tag: str | None = None
    line_comment = False
    block_depth = 0
    while index < len(script):
        char = script[index]
        next_char = script[index + 1] if index + 1 < len(script) else ""
        if line_comment:
            if char == "\n":
                line_comment = False
            index += 1
            continue
        if block_depth:
            if char == "/" and next_char == "*":
                block_depth += 1
                index += 2
            elif char == "*" and next_char == "/":
                block_depth -= 1
                index += 2
            else:
                index += 1
            continue
        if dollar_tag:
            if script.startswith(dollar_tag, index):
                index += len(dollar_tag)
                dollar_tag = None
            else:
                index += 1
            continue
        if quote:
            if char == quote:
                if next_char == quote:
                    index += 2
                else:
                    quote = None
                    index += 1
            elif char == "\\" and quote == "'":
                index += 2
            else:
                index += 1
            continue
        if char == "-" and next_char == "-":
            line_comment = True
            index += 2
        elif char == "/" and next_char == "*":
            block_depth = 1
            index += 2
        elif char in "'\"":
            quote = char
            index += 1
        elif char == "$":
            end = script.find("$", index + 1)
            if end >= 0 and (
                end == index + 1 or script[index + 1 : end].replace("_", "a").isalnum()
            ):
                dollar_tag = script[index : end + 1]
                index = end + 1
            else:
                index += 1
        elif char == ";":
            statement = script[start:index].strip()
            if statement:
                statements.append(statement)
            start = index + 1
            index += 1
        else:
            index += 1
    tail = script[start:].strip()
    if tail:
        statements.append(tail)
    if quote or dollar_tag or block_depth:
        raise ValueError("Unterminated SQL quote, dollar body, or block comment in frozen baseline")
    return statements


def upgrade() -> None:
    for script in MIGRATION_SQL:
        for statement in _split_sql(script):
            if statement.upper() in {"BEGIN", "BEGIN TRANSACTION", "COMMIT", "END"}:
                continue
            op.get_bind().exec_driver_sql(statement)


