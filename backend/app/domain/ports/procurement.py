"Операции хранения закупок, привязанные к единице работы вызывающего кода."

from typing import Any, Protocol


class ProcurementRepository(Protocol):
    async def request(self, identifier: str, *, lock: bool = False) -> Any | None: ...
    async def all_requests(self) -> list[Any]: ...
    async def create_request(self, values: dict[str, Any], items: list[dict[str, Any]]) -> Any: ...
    async def replace_request(
        self, row: Any, values: dict[str, Any], items: list[dict[str, Any]]
    ) -> Any: ...
    async def update_request_values(self, identifier: str, values: dict[str, Any]) -> None: ...
    async def supplier(self, identifier: str, *, active_only: bool = False) -> Any | None: ...
    async def create_supplier(self, values: dict[str, Any]) -> Any: ...
    async def options(self) -> dict[str, list[dict[str, Any]]]: ...
    async def references_exist(
        self, *, project_id: str | None, group_ids: tuple[str | None, ...]
    ) -> bool: ...
    async def create_contract(self, values: dict[str, Any]) -> Any: ...
    async def create_delivery(self, values: dict[str, Any], items: list[dict[str, Any]]) -> Any: ...
    async def delivery_item(self, identifier: str, *, lock: bool = False) -> Any | None: ...
    async def link_delivery_asset(self, delivery_item_id: str, asset_id: str) -> bool: ...
    async def uncapitalized_delivery_item_count(self, request_id: str) -> int: ...
    async def set_request_status(self, request_id: str, status: str) -> None: ...
