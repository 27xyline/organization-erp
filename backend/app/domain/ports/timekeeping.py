from __future__ import annotations

from datetime import date
from decimal import Decimal
from typing import Any, Protocol


class TimekeepingRepository(Protocol):
    async def get_entry(self, identifier: str, *, for_update: bool = False) -> Any | None: ...
    async def month_entries(self, year: int, month: int) -> list[Any]: ...
    async def month_timesheets(self, year: int, month: int) -> list[Any]: ...
    async def employee_options(self) -> list[Any]: ...
    async def project_options(self) -> list[dict[str, Any]]: ...
    async def reviewer_for(self, employee_id: str) -> dict[str, Any] | None: ...
    async def employee(self, identifier: str) -> Any | None: ...
    async def project(self, identifier: str) -> Any | None: ...
    async def task(self, identifier: str) -> Any | None: ...
    async def daily_hours(
        self, employee_id: str, work_date: date, exclude_id: str | None = None
    ) -> Decimal: ...
    async def timesheet(
        self, employee_id: str, year: int, month: int, *, for_update: bool = False
    ) -> Any | None: ...
    async def get_timesheet(self, identifier: str, *, for_update: bool = False) -> Any | None: ...
    async def save_entry(self, values: dict[str, Any], identifier: str | None = None) -> Any: ...
    async def delete_entry(self, identifier: str) -> None: ...
    async def save_timesheet(
        self, values: dict[str, Any], identifier: str | None = None
    ) -> Any: ...
